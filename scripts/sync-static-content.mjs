/* Keeps the pre-render homepage copy in index.html identical to what React
   renders, so people and crawlers always get the same words (no hidden text).

   Source of truth: the hero copy below (mirrors HeroOverlay.tsx), the section
   label/title/copy in src/config/sections.ts, and the closing CTA (mirrors the
   footer in ScrollSections.tsx). Runs before every build and rewrites the block
   between the STATIC-CONTENT markers. `node scripts/sync-static-content.mjs --check`
   exits 1 if index.html is out of date. */
import { readFileSync, writeFileSync } from 'node:fs'

const HERO_H1 = 'Your back office, automated.'
const HERO_P =
  'We build AI operations systems for real businesses: quoting, receipts, dispatch and daily reporting, running around the clock on the tools you already use. No migration, and you keep the source.'
const CTA_H2 = 'Get your evenings back. Start with an audit.'
const CTA_P =
  'Every engagement starts the same way: one week inside your operation, mapping where the hours actually go. You get a written plan of what an AI back-office would take off your plate and what it costs to build. Fixed scope, no lock-in, and the source code for everything we build for you is handed over, so the system that runs your business stays yours.'

const esc = (s) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;')
const unq = (s) => s.replace(/\\n/g, ' ').replace(/\\'/g, "'").replace(/\\"/g, '"')

const src = readFileSync(new URL('../src/config/sections.ts', import.meta.url), 'utf8')
const field = (block, name) => {
  const m = block.match(new RegExp(`\\n\\s+${name}: (?:'((?:[^'\\\\]|\\\\.)*)'|"((?:[^"\\\\]|\\\\.)*)")`))
  return m ? unq(m[1] ?? m[2]) : ''
}
const blocks = src.split(/\n  \{\n/).slice(1)
const sections = blocks
  .map((b) => ({ label: field(b, 'label'), title: field(b, 'title'), copy: field(b, 'copy') }))
  .filter((s) => s.title && s.copy)
if (sections.length < 5) throw new Error(`sync-static-content: parsed only ${sections.length} sections`)

const html = [
  '<!-- STATIC-CONTENT:START (generated by scripts/sync-static-content.mjs, do not edit by hand) -->',
  '    <main id="static-content">',
  `      <h1>${esc(HERO_H1)}</h1>`,
  `      <p>${esc(HERO_P)}</p>`,
  ...sections.flatMap((s) => [`      <h2>${esc(s.label)}: ${esc(s.title)}</h2>`, `      <p>${esc(s.copy)}</p>`]),
  `      <h2>${esc(CTA_H2)}</h2>`,
  `      <p>${esc(CTA_P)}</p>`,
  '      <p><a href="start/">Book an AI Ops Audit</a> · <a href="tel:+17809155471">780-915-5471</a> · <a href="mailto:hello@kr8tiv.ai">hello@kr8tiv.ai</a></p>',
  '      <ul>',
  '        <li><a href="services/">Services</a>: <a href="services/ai-training/">AI training &amp; courses</a>, <a href="services/company-brain/">Company Brain</a>, <a href="services/automations/">automations</a>, <a href="services/tool-integration/">tool integration</a>, <a href="services/evolve/">Evolve</a></li>',
  '        <li><a href="work/evolve/">Case study: Evolve Eco Blasting</a></li>',
  '        <li><a href="https://kr8tiv.io">Design by kr8tiv.io</a></li>',
  '      </ul>',
  '    </main>',
  '    <!-- STATIC-CONTENT:END -->',
].join('\n')

const indexPath = new URL('../index.html', import.meta.url)
const index = readFileSync(indexPath, 'utf8')
const re = /<!-- STATIC-CONTENT:START[\s\S]*?<!-- STATIC-CONTENT:END -->/
if (!re.test(index)) throw new Error('sync-static-content: markers not found in index.html')
const next = index.replace(re, html)
if (process.argv.includes('--check')) {
  if (next !== index) {
    console.error('index.html static content is out of date. Run: node scripts/sync-static-content.mjs')
    process.exit(1)
  }
  console.log('static content in sync')
} else {
  writeFileSync(indexPath, next)
  console.log(`static content synced (${sections.length} sections)`)
}
